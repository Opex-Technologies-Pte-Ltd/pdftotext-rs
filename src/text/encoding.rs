#[allow(clippy::needless_range_loop)] // table init by index is clearer as a range
fn ascii_latin1() -> [u32; 256] {
    let mut t = [0u32; 256];
    for i in 0x20..=0x7e {
        t[i] = i as u32;
    }
    for i in 0xa0..=0xff {
        t[i] = i as u32;
    }
    t
}

/// WinAnsiEncoding = code page 1252. ASCII 0x20–0x7E, Windows specials in
/// 0x80–0x9F, Latin-1 0xA0–0xFF.
fn winansi() -> [u32; 256] {
    let mut t = ascii_latin1();
    // 0x80–0x9F Windows-1252 assignments (undefined slots stay 0).
    let specials: [(u8, u32); 27] = [
        (0x80, 0x20AC), // €
        (0x82, 0x201A), // ‚
        (0x83, 0x0192), // ƒ
        (0x84, 0x201E), // „
        (0x85, 0x2026), // …
        (0x86, 0x2020), // †
        (0x87, 0x2021), // ‡
        (0x88, 0x02C6), // ˆ
        (0x89, 0x2030), // ‰
        (0x8A, 0x0160), // Š
        (0x8B, 0x2039), // ‹
        (0x8C, 0x0152), // Œ
        (0x8E, 0x017D), // Ž
        (0x91, 0x2018), // ‘
        (0x92, 0x2019), // ’
        (0x93, 0x201C), // “
        (0x94, 0x201D), // ”
        (0x95, 0x2022), // •
        (0x96, 0x2013), // –
        (0x97, 0x2014), // —
        (0x98, 0x02DC), // ˜
        (0x99, 0x2122), // ™
        (0x9A, 0x0161), // š
        (0x9B, 0x203A), // ›
        (0x9C, 0x0153), // œ
        (0x9E, 0x017E), // ž
        (0x9F, 0x0178), // Ÿ
    ];
    for (b, cp) in specials {
        t[b as usize] = cp;
    }
    // Annex D names 0xAD `hyphen`: a visible hyphen, not the invisible U+00AD.
    t[0xAD] = 0x2D;
    t
}

