#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn winansi_smart_quotes_and_euro() {
        let t = predefined("WinAnsiEncoding");
        assert_eq!(t[0x80], 0x20AC); // €
        assert_eq!(t[0x92], 0x2019); // ’ — the gap-#1 example
        assert_eq!(t[0x85], 0x2026); // … — not 0x0085
        assert_eq!(t[0x95], 0x2022); // •
        assert_eq!(t[0x41], 0x41); // ASCII A
        assert_eq!(t[0xE9], 0xE9); // Latin-1 é
        assert_eq!(t[0x81], 0); // undefined slot
    }

    #[test]
    fn mac_roman_differs_from_winansi() {
        let m = predefined("MacRomanEncoding");
        let w = predefined("WinAnsiEncoding");
        assert_eq!(m[0x80], 0xC4); // Ä
        assert_ne!(m[0x80], w[0x80]); // MacRoman 0x80 ≠ WinAnsi 0x80 (€)
        assert_eq!(m[0x41], 0x41); // ASCII
    }

    #[test]
    fn unknown_name_falls_back() {
        let t = predefined("MacExpertEncoding");
        assert_eq!(t[0x41], 0x41);
        assert_eq!(t[0xE9], 0xE9);
    }

    #[test]
    fn symbol_encoding_greek_and_math() {
        let t = predefined("SymbolEncoding");
        assert_eq!(t[0x57], 0x03A9); // Omega
        assert_eq!(t[0x6D], 0x03BC); // mu
        assert_eq!(t[0xB1], 0x00B1); // plusminus
        assert_eq!(t[0xA3], 0x2264); // lessequal
        assert_eq!(t[0x30], 0x30);
    }

    #[test]
    fn standard_encoding_high_half() {
        let t = predefined("StandardEncoding");
        assert_eq!(t[0xAE], 0xFB01); // fi
        assert_eq!(t[0xAF], 0xFB02); // fl
        assert_eq!(t[0x27], 0x2019); // quoteright
        assert_eq!(t[0xE1], 0x00C6); // AE
        assert_eq!(t[0xE9], 0x00D8); // Oslash, not Latin-1 é
        assert_eq!(t[0x41], 0x41);
    }
}
