//! Standard PDF encoding tables.
//!
//! A simple font with a named `/Encoding` (e.g. `WinAnsiEncoding`) and no full
//! `/Differences` array must be decoded through that encoding's byte→Unicode
//! table. Previously `predefined()` ignored the name and returned a generic
//! ASCII+Latin-1 table — which mangled WinAnsi's 0x80–0x9F (smart quotes,
//! ellipsis, bullet, Euro…) and was entirely wrong for MacRoman's 0x80–0xFF.
//!
//! Tables here are the public, fixed PDF/Adobe standard encodings (ISO 32000-2
//! Annex D, code-page 1252 for WinAnsi, the Mac OS Roman mapping for MacRoman).
//! Unknown/unmapped bytes are `0`.

/// Resolve a predefined encoding name to a 256-entry byte→Unicode table.
/// WinAnsi, MacRoman and Standard follow Annex D; MacExpert (small caps and
/// old-style figures, rare in text) and unknown names fall back to ASCII +
/// Latin-1.
pub fn predefined(name: &str) -> [u32; 256] {
    match name {
        "WinAnsiEncoding" => winansi(),
        "MacRomanEncoding" => mac_roman(),
        "StandardEncoding" => standard(),
        "SymbolEncoding" => symbol(),
        _ => ascii_latin1(),
    }
}

